"""Pin identity and attribution checks across reachable history."""
import contextlib
import importlib.util
import io
import os
import subprocess
import sys
import tempfile
from pathlib import Path
import unittest
from unittest.mock import patch

SPEC = importlib.util.spec_from_file_location("history", Path(__file__).with_name("history.py"))
HISTORY = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(HISTORY)


def record(message="Describe the change", **changes):
    fields = dict(author="repository-name", email="repository-email",
                  committer="repository-name", committer_email="repository-email")
    fields.update(changes)
    return (f"tree {'a'*40}\nauthor {fields['author']} <{fields['email']}> 0 +0000\n"
            f"committer {fields['committer']} <{fields['committer_email']}> 0 +0000\n\n{message}\0").encode()



def git_output(records):
    def output(command):
        if command[1:3] == ["config", "user.name"]:
            return b"repository-name\n"
        if command[1:3] == ["config", "user.email"]:
            return b"repository-email\n"
        return records
    return output


class HistoryTests(unittest.TestCase):
    def verify(self, records):
        with patch.object(HISTORY.subprocess, "check_output", side_effect=git_output(records)), \
                patch.object(HISTORY, "metadata", return_value=[("a"*40, b"commit", raw) for raw in records.split(b"\0") if raw]):
            with contextlib.redirect_stdout(io.StringIO()) as output:
                HISTORY.verify("HEAD")
            return output.getvalue()

    def test_multiple_valid_commits(self):
        self.assertIn("2 commits verified", self.verify(record() + record()))

    def test_wrong_identity_is_refused(self):
        for field in ("author", "email", "committer", "committer_email"):
            with self.subTest(field=field), self.assertRaisesRegex(ValueError, "identity"):
                self.verify(record(**{field: "different"}))

    def test_empty_message_is_refused(self):
        with self.assertRaisesRegex(ValueError, "empty"):
            self.verify(record(message="\n"))

    def test_attribution_is_refused(self):
        for message in ("Co-authored-by: other", "Generated with tooling", "AI-assisted change", "\U0001f916 change"):
            with self.subTest(message=message), self.assertRaisesRegex(ValueError, "attribution"):
                self.verify(record(message))

    def test_empty_range_is_valid(self):
        self.assertIn("0 commits verified", self.verify(b""))

    def test_product_words_are_allowed(self):
        self.assertIn("1 commits verified", self.verify(record(
            message="Let a coding agent promote a tested commit\nMCP assistant uplink; AI clients")))

    def test_prose_is_allowed_and_attribution_reports_line(self):
        for message in ("Check the manifests generated by the installer",
                        "Label AI-generated summaries in the run view",
                        "Test that Co-Authored-By: input is rejected"):
            with self.subTest(message=message):
                self.assertIn("1 commits verified", self.verify(record(message=message)))
        for phrase in ("Generated with tooling", "Generated by tooling", "Co-Authored-By: credit"):
            with self.subTest(phrase=phrase), self.assertRaisesRegex(ValueError, "message:3:.*remove the attribution"):
                self.verify(record(message="Subject\n\n  " + phrase))

    def test_generated_code_marker_is_not_attribution(self):
        self.assertIn("1 commits verified", self.verify(record("Code generated by a fixture; DO NOT EDIT.")))
        with self.assertRaisesRegex(ValueError, "attribution"):
            self.verify(record("Generated by fixture tooling"))

    def test_email_exemption_is_exact_bytes_in_header_fields_only(self):
        address = b"test@example.invalid"
        for variant in (address, address.upper(), b"test@EXAMPLE.INVALID", b"prefix-"+address):
            raw = b"author Test <"+variant+b"> 0 +0000\n\n"+address
            cleaned = HISTORY.public_metadata(raw, address)
            self.assertEqual((b"author Test <> 0 +0000" if variant == address else raw.split(b"\n\n")[0])+b"\n\n"+address, cleaned)
        raw = b"author test@example.invalid <test@example.invalid> 0 +0000\n\nmessage"
        self.assertIn(address, HISTORY.public_metadata(raw, address))

    def test_attribution_on_main_is_refused_from_a_clean_descendant(self):
        scratch = Path(os.environ.get("TMPDIR", Path.home()/".cache/go-tmp"))
        scratch.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(dir=scratch) as directory:
            def git(*arguments):
                subprocess.run(["git", *arguments], cwd=directory, check=True,
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            git("init", "-q", "-b", "main")
            git("config", "user.name", "fixture")
            git("config", "user.email", "fixture")
            git("commit", "--allow-empty", "-qm", "Generated with fixture tooling")
            git("checkout", "-qb", "clean-descendant")
            git("commit", "--allow-empty", "-qm", "Add a clean change")
            result = subprocess.run([sys.executable, "-I", HISTORY.__file__, "HEAD"],
                                    cwd=directory, text=True, capture_output=True, check=False)
            self.assertNotEqual(0, result.returncode)
            self.assertIn("attribution line", result.stderr)

    def test_every_invalid_commit_is_reported(self):
        with self.assertRaises(ValueError) as result:
            self.verify(record(author="different") + record(message=""))
        self.assertIn("identity",str(result.exception))
        self.assertIn("empty commit message",str(result.exception))

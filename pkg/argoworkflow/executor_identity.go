package argoworkflow

import (
	"fmt"
	"strings"
)

// ExecutorIdentityVolumeName and ExecutorIdentityMountPath belong exclusively to
// the server-delivered Argo executor identity, never authored containers.
const (
	ExecutorIdentityVolumeName = "exec-sa-token"
	ExecutorIdentityMountPath  = "/var/run/secrets/kubernetes.io/serviceaccount"
)

func admitExecutorContainerName(location, name string, main bool) []error {
	if serverOwnedName(name) {
		return []error{fmt.Errorf("argoworkflow: %s.name %q uses the reserved server-owned oberth- prefix", location, name)}
	}
	if strings.Contains(name, "{{") || name == "init" || name == "wait" || (name == "main" && !main) {
		return []error{fmt.Errorf("argoworkflow: %s.name %q is reserved for the Argo executor; container names must be literal and helpers cannot use init, wait or main", location, name)}
	}
	return nil
}

func admitExecutorVolumeName(location, name string) []error {
	if serverOwnedName(name) {
		return []error{fmt.Errorf("argoworkflow: %s.name %q uses the reserved server-owned oberth- prefix", location, name)}
	}
	if reservedArgoVolumeName(name) || strings.Contains(name, "{{") {
		return []error{fmt.Errorf("argoworkflow: %s.name %q can select the reserved executor identity volume or Argo scratch and is not admitted", location, name)}
	}
	return nil
}

func serverOwnedName(name string) bool {
	return strings.HasPrefix(name, "oberth-")
}

// Names generated by the pinned v4.0.8 controller, including its plugin
// namespace. Authored references must never alias controller scratch or identity.
func reservedArgoVolumeName(name string) bool {
	switch name {
	case ExecutorIdentityVolumeName, "tmp-dir-argo", "var-run-argo", "argo-staging", "argo-env-config", "input-artifacts", "kubeconfig":
		return true
	default:
		return strings.HasPrefix(name, "artifact-plugin-")
	}
}
